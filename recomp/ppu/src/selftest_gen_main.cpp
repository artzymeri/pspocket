// ppu-selftest-gen: builds the self-test benchmark program (synthetic::build_selftest_bench) and writes
//   --bin FILE     the raw image (input of ppu-lift)
//   --seeds FILE   its seeds
//   --c FILE       the image as a C array (compiled into the self-test library, also by the iOS app)
//   --h FILE       its header: load address, entry, benchmark parameters and the expected result
// The expected result is computed natively (synthetic::bench_reference) from the same buffer pattern the probe
// writes (PS_SELFTEST_PPU_PATTERN).

#include <cstdio>
#include <fstream>
#include <format>
#include <string>
#include <vector>

#include "pspocket/recomp/ppu/lifter.hpp"
#include "pspocket/recomp/ppu/synthetic.hpp"

using namespace pspocket;
using namespace pspocket::recomp::ppu;

namespace {

constexpr u32 kBase = 0x00010000;
constexpr u32 kWords = 16384;   // 64 KB buffer
constexpr u32 kIterations = 96;
constexpr u32 kFibN = 22;

u32 pattern(u32 i) { return (i * 0x9E3779B1u) ^ 0x5A5A5A5Au; }

bool write(const std::string& path, const std::string& content)
{
    if (path.empty()) return true;
    std::ifstream in(path, std::ios::binary);
    if (in) {
        std::string old((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        if (old == content) return true;
    }
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out << content;
    return static_cast<bool>(out);
}

} // namespace

int main(int argc, char** argv)
{
    std::string bin, seeds, c, h;
    for (int i = 1; i + 1 < argc; i += 2) {
        const std::string arg = argv[i];
        if (arg == "--bin") bin = argv[i + 1];
        else if (arg == "--seeds") seeds = argv[i + 1];
        else if (arg == "--c") c = argv[i + 1];
        else if (arg == "--h") h = argv[i + 1];
        else {
            std::fprintf(stderr, "ppu-selftest-gen: unknown option %s\n", arg.c_str());
            return 2;
        }
    }

    const synthetic::Program prog = synthetic::build_selftest_bench(kBase);
    std::vector<u32> buffer(kWords);
    for (u32 i = 0; i < kWords; i++) buffer[i] = pattern(i);
    const u64 expected = synthetic::bench_reference(buffer, kIterations, kFibN);

    const std::string raw(prog.bytes.begin(), prog.bytes.end());
    std::string seed_text;
    for (const Seed& s : prog.seeds) seed_text += std::format("0x{:08x} {}\n", s.addr, s.name);

    std::string header = "/* Generated by ppu-selftest-gen (recomp/ppu). Do not edit. */\n"
                         "#ifndef PS_SELFTEST_PPU_IMAGE_H\n#define PS_SELFTEST_PPU_IMAGE_H\n\n#include <stdint.h>\n\n";
    header += std::format("#define PS_SELFTEST_PPU_IMAGE_BASE 0x{:08x}u\n", prog.base);
    header += std::format("#define PS_SELFTEST_PPU_IMAGE_SIZE {}u\n", prog.bytes.size());
    header += std::format("#define PS_SELFTEST_PPU_ENTRY 0x{:08x}u /* bench(buf, words, iterations, fib_n) */\n",
        prog.symbol("bench"));
    header += std::format("#define PS_SELFTEST_PPU_WORDS {}u\n#define PS_SELFTEST_PPU_ITERATIONS {}u\n#define PS_SELFTEST_PPU_FIB_N {}u\n",
        kWords, kIterations, kFibN);
    header += "/* Buffer word i before the run (host order; stored big-endian in guest memory). */\n"
              "#define PS_SELFTEST_PPU_PATTERN(i) ((uint32_t)((uint32_t)(i) * 0x9E3779B1u) ^ 0x5A5A5A5Au)\n";
    header += std::format("#define PS_SELFTEST_PPU_EXPECTED 0x{:016x}ull /* bench() result, computed natively */\n\n", expected);
    header += "#ifdef __cplusplus\nextern \"C\" {\n#endif\nextern const uint8_t ps_selftest_ppu_image[PS_SELFTEST_PPU_IMAGE_SIZE];\n"
              "#ifdef __cplusplus\n}\n#endif\n\n#endif\n";

    std::string source = "/* Generated by ppu-selftest-gen (recomp/ppu). Do not edit. */\n#include \"ps_selftest_ppu_image.h\"\n\n"
                         "const uint8_t ps_selftest_ppu_image[PS_SELFTEST_PPU_IMAGE_SIZE] = {\n";
    for (usize i = 0; i < prog.bytes.size(); i++) {
        source += std::format("{}0x{:02x},", i % 16 == 0 ? "    " : " ", prog.bytes[i]);
        if (i % 16 == 15 || i + 1 == prog.bytes.size()) source += "\n";
    }
    source += "};\n";

    if (!write(bin, raw) || !write(seeds, seed_text) || !write(h, header) || !write(c, source)) {
        std::fprintf(stderr, "ppu-selftest-gen: cannot write output\n");
        return 1;
    }
    return 0;
}
