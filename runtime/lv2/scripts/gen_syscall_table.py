#!/usr/bin/env python3
"""Generate runtime/lv2/src/syscall_table.inc from recomp/common/data/syscalls.txt.

The runtime must not depend on recomp/ (the iOS app compiles only runtime/), so the syscall names are copied into
a committed include file. Run this after the NID/syscall harvest changes syscalls.txt:

    python3 runtime/lv2/scripts/gen_syscall_table.py            # regenerate
    python3 runtime/lv2/scripts/gen_syscall_table.py --check    # exit 1 if the committed file is stale

Output: one `{number, "name"},` line per syscall, sorted by number. Names only; no behaviour.
"""

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "recomp" / "common" / "data" / "syscalls.txt"
DST = ROOT / "runtime" / "lv2" / "src" / "syscall_table.inc"
MAX_SYSCALL = 1024  # lv2 has 1024 syscall slots (RPCS3 lv2.cpp g_ppu_syscall_table)


def parse(text: str) -> list[tuple[int, str]]:
    entries: dict[int, str] = {}
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 2 or not parts[0].isdigit():
            raise SystemExit(f"{SRC}:{lineno}: expected `number name`, got {raw!r}")
        number, name = int(parts[0]), parts[1]
        if number >= MAX_SYSCALL:
            raise SystemExit(f"{SRC}:{lineno}: syscall number {number} out of range")
        if not name.replace("_", "").isalnum():
            raise SystemExit(f"{SRC}:{lineno}: suspicious name {name!r}")
        if number in entries and entries[number] != name:
            raise SystemExit(f"{SRC}:{lineno}: syscall {number} named twice ({entries[number]}, {name})")
        entries[number] = name
    return sorted(entries.items())


def render(entries: list[tuple[int, str]]) -> str:
    out = [
        "// lv2 syscall names, number -> name. GENERATED by runtime/lv2/scripts/gen_syscall_table.py from",
        "// recomp/common/data/syscalls.txt (harvested from RPCS3 rpcs3/Emu/Cell/lv2/lv2.cpp, GPLv2). Do not edit.",
        "// Included by runtime/lv2/src/dispatch.cpp inside an array initializer.",
    ]
    out += [f'{{{number}, "{name}"}},' for number, name in entries]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed table is out of date")
    args = ap.parse_args()
    text = render(parse(SRC.read_text()))
    if args.check:
        current = DST.read_text() if DST.exists() else ""
        if current != text:
            print(f"{DST.relative_to(ROOT)} is stale; run {pathlib.Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    DST.write_text(text)
    print(f"wrote {DST.relative_to(ROOT)} ({text.count(chr(10)) - 3} syscalls)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
