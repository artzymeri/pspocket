#!/usr/bin/env python3
"""Generate runtime/lv2/src/syscall_null.inc: the lv2 syscalls RPCS3 answers with null_func (D-166).

RPCS3's g_ppu_syscall_table (rpcs3/Emu/Cell/lv2/lv2.cpp, GPLv2) binds a syscall to a real function (BIND_SYSC), to
null_func (named with NULL_FUNC or not: it logs once and returns CELL_OK), or to uns_func (unused: CELL_ENOSYS). pspocket
answers every null_func slot it does not implement as RPCS3 does, so a game calling one goes on instead of meeting
ENOSYS. The runtime does not read RPCS3's source (the iOS app compiles only runtime/), so the slots are copied into a
committed include:

    python3 runtime/lv2/scripts/gen_null_syscalls.py RPCS3_DIR            # regenerate
    python3 runtime/lv2/scripts/gen_null_syscalls.py RPCS3_DIR --check    # exit 1 if the committed file is stale

Output: one `{number, "what"},` line per null_func slot, sorted by number: the NULL_FUNC name, or for an unnamed slot
what RPCS3's comment on that line names (a commented-out BIND_SYSC and the line's ROOT/DBG/UNS tags).
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
DST = ROOT / "runtime" / "lv2" / "src" / "syscall_null.inc"
TABLE_SIZE = 1024
ENTRY = re.compile(r"^(?:(BIND_SYSC|NULL_FUNC)\s*\(\s*(\w*)\s*\)|(null_func|uns_func))$")


def harvest(rpcs3: pathlib.Path) -> list[tuple[int, str]]:
    path = rpcs3 / "rpcs3" / "Emu" / "Cell" / "lv2" / "lv2.cpp"
    raw = path.read_text(encoding="utf-8", errors="replace")
    anchor = raw.find("g_ppu_syscall_table")
    open_index = raw.find("{", anchor)
    close_index = raw.find("};", open_index)
    if anchor < 0 or open_index < 0 or close_index < 0:
        raise SystemExit(f"{path}: cannot find g_ppu_syscall_table")
    body = re.sub(r"/\*.*?\*/", "", raw[open_index + 1 : close_index], flags=re.S)
    out: list[tuple[int, str]] = []
    index = 0
    for line in body.split("\n"):
        code, _, comment = line.partition("//")
        tokens = [t.strip() for t in code.split(",") if t.strip()]
        hint = ""
        m = re.search(r"BIND_SYSC\(\s*([\w.]+)\s*\)", comment)
        if m:
            hint = m.group(1)
        tags = " ".join(t for t in ("ROOT", "DBG", "UNS", "DEX", "DECR") if re.search(r"\b" + t + r"\b", comment))
        for token in tokens:
            e = ENTRY.match(token)
            if not e:
                raise SystemExit(f"{path}: unexpected syscall table entry {token!r}")
            if e.group(1) == "NULL_FUNC":
                out.append((index, e.group(2)))
            elif e.group(3) == "null_func":
                what = hint if len(tokens) == 1 and hint else "unnamed"
                out.append((index, f"{what} ({tags})" if tags else what))
            index += 1
    if index != TABLE_SIZE:
        raise SystemExit(f"{path}: syscall table has {index} entries, expected {TABLE_SIZE}")
    return out


def render(entries: list[tuple[int, str]]) -> str:
    lines = [
        "// lv2 syscalls RPCS3 answers with null_func: a log, then CELL_OK (D-166). GENERATED by",
        "// runtime/lv2/scripts/gen_null_syscalls.py from RPCS3 rpcs3/Emu/Cell/lv2/lv2.cpp (GPLv2). Do not edit.",
        "// Included by runtime/lv2/src/kernel.cpp inside an array initializer.",
    ]
    lines += [f'{{{number}, "{what}"}},' for number, what in entries]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("rpcs3_dir", type=pathlib.Path)
    ap.add_argument("--check", action="store_true", help="fail if the committed table is out of date")
    args = ap.parse_args()
    text = render(harvest(args.rpcs3_dir))
    if args.check:
        if not DST.exists() or DST.read_text() != text:
            print(f"gen_null_syscalls: {DST} is out of date", file=sys.stderr)
            return 1
        return 0
    DST.write_text(text)
    print(f"gen_null_syscalls: {text.count(chr(10)) - 3} null_func slots -> {DST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
