#!/usr/bin/env python3
"""Generate runtime/lv2/src/syscall_stub.inc: the lv2 syscalls RPCS3 binds to a stub (D-184).

RPCS3's g_ppu_syscall_table (rpcs3/Emu/Cell/lv2/lv2.cpp) binds many syscalls with BIND_SYSC to a function whose body is
only a log and `return X;` with X a constant (CELL_OK nearly always): sys_fs_chown, sys_fs_link, sys_fs_truncate2, the
trace and storage families and more. Games run on RPCS3 with those answers, so pspocket answers them the same way, with
a log of the first call, as it answers RPCS3's null_func slots (D-166, gen_null_syscalls.py). A syscall pspocket
implements (PS_LV2_BIND) always takes the slot first.

    python3 runtime/lv2/scripts/gen_stub_syscalls.py RPCS3_DIR            # regenerate
    python3 runtime/lv2/scripts/gen_stub_syscalls.py RPCS3_DIR --check    # exit 1 if the committed file is stale

A function is a stub by runtime/hle/scripts/gen_rpcs3_stubs.py's rule (its body, comments, log statements and
UNIMPLEMENTED_FUNC removed, is `return X;`), with two statements that change nothing for a constant answer also
removed: `ppu.state += cpu_flag::wait;` and `lv2_obj::sleep(ppu);` (or `cpu`). A void stub is left out (a syscall's r3 is its
result).

Output: one `{number, "name", 0xR3},` line per stub, sorted by number; R3 as gen_rpcs3_stubs.py computes it.
"""

import argparse
import importlib.util
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
DST = ROOT / "runtime" / "lv2" / "src" / "syscall_stub.inc"
TABLE_SIZE = 1024
ENTRY = re.compile(r"^(?:(BIND_SYSC|NULL_FUNC)\s*\(\s*(\w*)\s*\)|(null_func|uns_func))$")
NO_EFFECT = re.compile(r"\b(?:ppu|cpu)\.state\s*\+=\s*cpu_flag::wait\s*;|\blv2_obj::sleep\s*\(\s*(?:ppu|cpu)\s*\)\s*;")

sys.dont_write_bytecode = True  # no __pycache__ beside gen_rpcs3_stubs.py
_spec = importlib.util.spec_from_file_location("gen_rpcs3_stubs", ROOT / "runtime" / "hle" / "scripts" / "gen_rpcs3_stubs.py")
stubs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(stubs)


def table(rpcs3: pathlib.Path) -> dict[int, str]:
    path = rpcs3 / "rpcs3" / "Emu" / "Cell" / "lv2" / "lv2.cpp"
    raw = path.read_text(encoding="utf-8", errors="replace")
    anchor = raw.find("g_ppu_syscall_table")
    open_index = raw.find("{", anchor)
    close_index = raw.find("};", open_index)
    if anchor < 0 or open_index < 0 or close_index < 0:
        raise SystemExit(f"{path}: cannot find g_ppu_syscall_table")
    body = re.sub(r"/\*.*?\*/", "", raw[open_index + 1 : close_index], flags=re.S)
    bound: dict[int, str] = {}
    index = 0
    for line in body.split("\n"):
        code = line.partition("//")[0]
        for token in (t.strip() for t in code.split(",") if t.strip()):
            e = ENTRY.match(token)
            if not e:
                raise SystemExit(f"{path}: unexpected syscall table entry {token!r}")
            if e.group(1) == "BIND_SYSC":
                bound[index] = e.group(2)
            index += 1
    if index != TABLE_SIZE:
        raise SystemExit(f"{path}: syscall table has {index} entries, expected {TABLE_SIZE}")
    return bound


def harvest(rpcs3: pathlib.Path) -> list[tuple[int, str, int]]:
    consts = stubs.error_constants(rpcs3)
    defs: dict[str, tuple[str, str]] = {}
    for path in sorted((rpcs3 / "rpcs3" / "Emu" / "Cell").rglob("*.cpp")):
        if "Modules" in path.parts:
            continue
        src = stubs.strip_comments(path.read_text(encoding="utf-8", errors="replace"))
        for name, (ret, body) in stubs.definitions(src).items():
            defs.setdefault(name, (ret, body))
    # Aliases in the headers: `constexpr auto sys_console_write2 = sys_console_write;`.
    for path in sorted((rpcs3 / "rpcs3" / "Emu" / "Cell" / "lv2").glob("*.h")):
        for m in re.finditer(r"constexpr\s+auto\s+(\w+)\s*=\s*(\w+)\s*;", path.read_text(errors="replace")):
            if m.group(2) in defs:
                defs.setdefault(m.group(1), defs[m.group(2)])
    out = []
    for number, name in sorted(table(rpcs3).items()):
        if name not in defs:
            continue
        ret, body = defs[name]
        result = stubs.stub_result(ret, NO_EFFECT.sub("", body), consts)
        if result is not None and result[1]:
            out.append((number, name, result[0]))
    return out


def render(entries: list[tuple[int, str, int]]) -> str:
    lines = [
        "// lv2 syscalls RPCS3 binds to a stub: a log, then a constant (D-184). GENERATED by",
        "// runtime/lv2/scripts/gen_stub_syscalls.py from RPCS3 rpcs3/Emu/Cell/lv2/*.cpp (GPLv2). Do not edit.",
        "// Included by runtime/lv2/src/kernel.cpp inside an array initializer.",
    ]
    lines += [f'{{{number}, "{name}", 0x{r3:X}}},' for number, name, r3 in entries]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("rpcs3_dir", type=pathlib.Path)
    ap.add_argument("--check", action="store_true", help="fail if the committed table is out of date")
    args = ap.parse_args()
    text = render(harvest(args.rpcs3_dir))
    if args.check:
        if not DST.exists() or DST.read_text() != text:
            print(f"gen_stub_syscalls: {DST} is out of date", file=sys.stderr)
            return 1
        return 0
    DST.write_text(text)
    print(f"gen_stub_syscalls: {text.count(chr(10)) - 3} stub syscalls -> {DST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
