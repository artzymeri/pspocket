# Writes runtime/hle/src/l10n_tables.hpp from tables.py (public mapping data, see there) packed by pack.py.
import base64, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import tables as T, pack

ORDER = [('jis0208', 'JIS X 0208 as cp932 reads it: rows 1-8, 16-84 (to 84-6)'),
         ('row13', "cp932's NEC row 13"),
         ('necsel', "cp932's NEC-selected IBM extensions, rows 89-92 (SJIS ED40-EEFC)"),
         ('ibmext', "cp932's IBM extensions, SJIS FA40-FC4B"),
         ('jis0212', 'JIS X 0212 rows 2, 6, 7, 9-11, 16-77 to EDE3 (euc_jp; A2B7 and A2C3 as Microsoft reads them)'),
         ('ksx1001', 'KS X 1001 rows A1-AC, B0-C8, CA-FD (cp949, and A2E8 U+327E)'),
         ('uhc1', "cp949's extension, leads 81-A0 (trails 41-5A, 61-7A, 81-FE)"),
         ('uhc2', "cp949's extension, leads A1-C6 (trails 41-5A, 61-7A, 81-A0), to C652"),
         ('gb2312', 'GB2312 rows A1-A9, B0-F7: the cells GB2312 assigns, as gbk reads them'),
         ('gbkrows', "gbk's rows A2, A6, A8 (GB2312's and GBK's cells)"),
         ('gbk3', "gbk's GBK/3, leads 81-A0 (trails 40-7E, 80-FE)"),
         ('gbk4', "gbk's GBK/4 and /5, leads A8-FE (trails 40-7E, 80-A0), to FE4F"),
         ('gbrows18030', "gb18030's rows A2, A4-A9 (A8BF as GB18030-2000: U+E7C8)"),
         ('gbd7', "gb18030's row D7"),
         ('gba8', "gb18030's leads A8-A9, trails 40-7E, 80-A0"),
         ('gbfe', "gb18030's lead FE, trails 40-7E, 80-A0"),
         ('big5', 'Big5 leads A1-C6, C9-F9 as cp950 reads them, without ETEN row C6A1-C6FE'),
         ('arib13', "ARIB STD-B24's kanji set rows 1-3 (JIS X 0208's, with ARIB's non-spacing marks as combining)"),
         ('aribadd', "ARIB STD-B24's additional symbols, rows 85-86 and 90-94"),
         ('sbcs', 'The upper halves of the 35 single-byte code pages, in code page order')]

out = []
w = out.append
w('#pragma once')
w('')
w('// cellL10n\'s mapping tables (D-517), generated from public mapping data only: Python\'s codecs (the Unicode')
w('// consortium\'s and the vendors\' published tables: cp932, euc_jp, cp949, gbk, gb2312, gb18030, cp950, ISO 8859-x and')
w('// the DOS/Windows code pages) and libaribcaption\'s ARIB STD-B24 additional-symbol table (MIT licence). Where Sony\'s')
w('// libl10n reads a cell otherwise, the comparison (tests/hle/test_l10n.cpp) found it and the generator patches that')
w('// cell (D-517 names each patch). Generated by scripts/l10n/emit.py; do not edit by hand.')
w('//')
w('// Each table is a byte stream in base64, unpacked once (cellL10n.cpp unpack()). The stream keeps `last`, the last value')
w('// that was not FFFF (starting at 0): 00-3F n+1 values last+1, last+2, ...; 40-5F n+1 FFFF (unassigned) values;')
w('// 60-BF one value last+1+(t-0x90); C0-DF, b: one value last+1+((t&0x1F)<<8|b)-0x1000; E0, h, l: the value h<<8|l.')
w('')
w('namespace pspocket::hle::l10n_data {')
w('')
w('struct Packed {')
w('    const char* base64;')
w('    unsigned count; // u16 values')
w('};')
w('')
names = []
for name, desc in ORDER:
    t = getattr(T, name)
    b = base64.b64encode(pack.pack(t)).decode()
    ident = 'k' + ''.join(p.capitalize() for p in name.split('_'))
    names.append((ident, len(t)))
    w(f'// {desc}: {len(t)} values.')
    w(f'inline constexpr char {ident}[] =')
    for i in range(0, len(b), 112):
        w(f'    "{b[i:i + 112]}"' + (';' if i + 112 >= len(b) else ''))
    w('')
w('inline constexpr Packed kTables[] = {')
for ident, n in names:
    w(f'    {{{ident}, {n}}},')
w('};')
w('')
w('// GB18030\'s four-byte cells Sony\'s module serves: CJK Extension A (U+3400-U+4DB5) where it has no two-byte cell, as')
w('// gb18030 gives them: {first linear index, first UCS-2 code, count}.')
w('struct Gb18030Range {')
w('    unsigned short linear, ucs;')
w('    unsigned count;')
w('};')
w('inline constexpr Gb18030Range kGb18030Ranges[] = {')
line = '   '
for L, u, n in T.gbranges:
    item = f' {{{L}, 0x{u:04X}, {n}}},'
    if len(line) + len(item) > 118: w(line); line = '   '
    line += item
w(line)
w('};')
w('')
w('} // namespace pspocket::hle::l10n_data')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
