#!/usr/bin/env python3
"""A bench route (relative steps, named button sequences) to a pspocket-boot --press-file (bench, D-1060).

    scripts/route.py ROUTE > press.txt

Route lines ('#' starts a comment):
    at T          the clock to T seconds since the boot
    wait S        the clock forward S seconds
    seq NAME      a named sequence (games/<title>/bench/sequences.txt or below), 0.45 s apart, each held 0.15 s
    hold BTN S    BTN held S seconds from now; the clock moves on S
    with BTN S    BTN held S seconds from now; the clock stays (held together with the next step)
    tap BTN       BTN for 0.25 s; the clock moves on 0.6 s
Buttons are pad_script's names (cross, circle, square, triangle, l1, l2, r1, r2, up, down, left, right, start, select,
ls-up, rs-left, ...). The presses are timed by the wall clock until the press scripts follow game time.
"""
import os
import sys


def sequences(route_path):
    """Named sequences: sequences.txt beside the route ("NAME: button button ..." a line)."""
    seq = {}
    path = os.path.join(os.path.dirname(os.path.abspath(route_path)), "sequences.txt")
    if os.path.exists(path):
        for raw in open(path):
            line = raw.split("#", 1)[0].strip()
            if ":" in line:
                name, buttons = line.split(":", 1)
                seq[name.strip()] = buttons.split()
    return seq


def compile_route(path):
    seq = sequences(path)
    t, out = 0.0, []
    for n, raw in enumerate(open(path), 1):
        line = raw.split("#", 1)[0].split()
        if not line:
            continue
        op, args = line[0], line[1:]
        if op == "at":
            t = float(args[0])
        elif op == "wait":
            t += float(args[0])
        elif op == "seq":
            if args[0] not in seq:
                sys.exit(f"{path}:{n}: no sequence named {args[0]} (sequences.txt)")
            for b in seq[args[0]]:
                out.append(f"{b}@{t:.2f}:0.15")
                t += 0.45
        elif op in ("hold", "with"):
            out.append(f"{args[0]}@{t:.2f}:{float(args[1]):g}")
            if op == "hold":
                t += float(args[1])
        elif op == "tap":
            out.append(f"{args[0]}@{t:.2f}")
            t += 0.6
        else:
            sys.exit(f"{path}:{n}: unknown step {op}")
    lines = [f"# generated by scripts/route.py from {os.path.basename(path)}"]
    lines += [" ".join(out[i:i + 10]) for i in range(0, len(out), 10)]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.stdout.write(compile_route(sys.argv[1]))
