#!/usr/bin/env python3
"""Writes the SELF key table the build carries (D-121) from RPCS3's Crypto/key_vault.cpp, and the firmware update
packages' key (D-156), the NPD files' keys (D-165), the PSN licence keys (D-580) and the PS3 packages' keys (D-583)
from key_vault.h, and libsysmodule's key for its export 0x59521326 (D-639) from Emu/Cell/Modules/cellSysmodule.cpp.

usage: self-keys.py RPCS3_DIR OUT.cpp

RPCS3_DIR is an RPCS3 source tree (the directory holding rpcs3/Crypto, or rpcs3/Crypto's parent). The output is a
C++ file defining pspocket::recomp::builtin_self_keys(): one entry per sk_*_arr entry, in key_vault.cpp's order
(KeyVault::FindSelfKey takes the first match). It goes in the build directory only: keys never go into the repository
(CLAUDE.md rule 1). Without the source tree the table is empty, and the build cannot decrypt executables (it says so
when asked to). The keys are never printed.
"""
import pathlib
import re
import sys

NPD_KEYS = ("SDAT_KEY", "EDAT_KEY_0", "EDAT_KEY_1", "EDAT_HASH_0", "EDAT_HASH_1", "EDAT_IV")
# recomp::NpdrmKeys' order (pspocket/recomp/npdrm.hpp).
NPDRM_KEYS = ("RAP_KEY", "RAP_PBOX", "RAP_E1", "RAP_E2", "NP_KLIC_FREE", "NP_KLIC_KEY", "NP_OMAC_KEY_2", "NP_OMAC_KEY_3")
# recomp::PkgKeys' order (pspocket/recomp/pkg.hpp).
PKG_KEYS = ("PKG_AES_KEY", "PKG_AES_KEY_IDU")

KEY_TYPES = {"KEY_LV0": 1, "KEY_LV1": 2, "KEY_LV2": 3, "KEY_APP": 4, "KEY_ISO": 5, "KEY_LDR": 6, "KEY_UNK7": 7,
             "KEY_NPDRM": 8}

# sk_*_arr.emplace_back(ver_start, ver_end, rev, KEY_x, "erk", "riv", "pub", "priv", curve_type)
ENTRY = re.compile(
    r"sk_(\w+?)_arr\.emplace_back\(\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,"
    r"\s*(KEY_\w+)\s*,\s*\"([0-9A-Fa-f]*)\"\s*,\s*\"([0-9A-Fa-f]*)\"", re.S)


def find_key_vault(root: pathlib.Path):
    for candidate in (root / "rpcs3" / "Crypto" / "key_vault.cpp", root / "Crypto" / "key_vault.cpp"):
        if candidate.is_file():
            return candidate
    return None


def sysmodule_key(root: pathlib.Path) -> bytes:
    """cellSysmodule.cpp's KEY_UNK (sixteen character or number constants), the key cellSysmodule_0x59521326 decrypts
    the OpenPSID with (D-639); b"" when the file or the array is not there or is not sixteen bytes."""
    for candidate in (root / "rpcs3" / "Emu" / "Cell" / "Modules" / "cellSysmodule.cpp",
                      root / "Emu" / "Cell" / "Modules" / "cellSysmodule.cpp"):
        if not candidate.is_file():
            continue
        m = re.search(r"\bKEY_UNK\s*\{([^}]*)\}", candidate.read_text(encoding="utf-8", errors="replace"))
        if not m:
            return b""
        data = bytearray()
        for item in (t.strip() for t in m.group(1).split(",")):
            if not item:
                continue
            char = re.fullmatch(r"'([ -&(-\[\]-~])'", item)  # a printable character but ' and \
            hex_number = re.fullmatch(r"0[xX]([0-9A-Fa-f]{1,2})", item)
            decimal = re.fullmatch(r"[0-9]{1,3}", item)
            if char:
                data.append(ord(char.group(1)))
            elif hex_number:
                data.append(int(hex_number.group(1), 16))
            elif decimal and int(item, 10) < 256:
                data.append(int(item, 10))
            else:
                return b""
        return bytes(data) if len(data) == 16 else b""
    return b""


def c_bytes(hex_text: str, size: int) -> str:
    data = bytes.fromhex(hex_text).ljust(size, b"\0")[:size]
    return "{" + ", ".join(f"0x{b:02x}" for b in data) + "}"


def sixteen_byte_arrays(text_h: str, names) -> str:
    """key_vault.h's constexpr byte arrays `names` (16 bytes each) as an initializer list ending in `true`, or "" when
    any is missing."""
    values = []
    for name in names:
        m = re.search(r"\b" + name + r"\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}", text_h) if text_h else None
        data = bytes(int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1))) if m else b""
        if len(data) != 16:
            return ""
        values.append(c_bytes(data.hex(), 16))
    return ", ".join(values) + ", true"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip().splitlines()[2], file=sys.stderr)
        return 64
    root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    vault = find_key_vault(root) if str(root) else None
    lines = ["// Generated by scripts/self-keys.py from RPCS3's Crypto/key_vault.cpp. Build directory only: never commit",
             "// (CLAUDE.md rule 1).",
             "#include \"pspocket/recomp/npd.hpp\"",
             "#include \"pspocket/recomp/npdrm.hpp\"",
             "#include \"pspocket/recomp/pkg.hpp\"",
             "#include \"pspocket/recomp/self_decrypt.hpp\"",
             "#include \"pspocket/recomp/sysmodule_key.hpp\"",
             "",
             "namespace pspocket::recomp {",
             "namespace {",
             "// The first entry holds the place: the table may be empty.",
             "constexpr SelfKey kKeys[] = {",
             "{0, 0, 0, 0, {}, {}},"]
    count = 0
    if vault:
        for m in ENTRY.finditer(vault.read_text(encoding="utf-8")):
            kind = KEY_TYPES.get(m.group(5))
            if kind is None or len(m.group(6)) != 64 or len(m.group(7)) != 32:
                continue
            lines.append(f"{{{kind}, {m.group(2)}, {m.group(3)}, {m.group(4)}, {c_bytes(m.group(6), 32)}, "
                         f"{c_bytes(m.group(7), 16)}}},")
            count += 1
    # The firmware update packages' key (key_vault.h SCEPKG_ERK, SCEPKG_RIV: constexpr byte arrays), for installing
    # /dev_flash from PS3UPDAT.PUP (D-156).
    package = ""
    header = vault.with_suffix(".h") if vault else None
    text_h = header.read_text(encoding="utf-8") if header and header.is_file() else ""
    if text_h:
        arrays = {}
        for name in ("SCEPKG_ERK", "SCEPKG_RIV"):
            m = re.search(name + r"\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}", text_h)
            if m:
                arrays[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1)))
        if len(arrays.get("SCEPKG_ERK", b"")) == 32 and len(arrays.get("SCEPKG_RIV", b"")) == 16:
            package = f"{c_bytes(arrays['SCEPKG_ERK'].hex(), 32)}, {c_bytes(arrays['SCEPKG_RIV'].hex(), 16)}, true"
    # The NPD files' keys (key_vault.h SDAT_KEY, EDAT_KEY_0/1, EDAT_HASH_0/1, EDAT_IV), for a game's SDATA files
    # (D-165), in recomp::NpdKeys' order; the PSN licence keys (D-580), in recomp::NpdrmKeys' order; and the PS3
    # packages' keys (D-583), in recomp::PkgKeys' order.
    npd = sixteen_byte_arrays(text_h, NPD_KEYS)
    npdrm = sixteen_byte_arrays(text_h, NPDRM_KEYS)
    pkg = sixteen_byte_arrays(text_h, PKG_KEYS)
    # libsysmodule's key for its export 0x59521326 (cellSysmodule.cpp KEY_UNK), for cellSysmodule_0x59521326 (D-639).
    sysmodule = sysmodule_key(root) if sys.argv[1] else b""
    lines += ["};", f"constexpr PackageKey kPackageKey = {{{package}}};" if package else "constexpr PackageKey kPackageKey{};",
              f"constexpr NpdKeys kNpdKeys = {{{npd}}};" if npd else "constexpr NpdKeys kNpdKeys{};",
              f"constexpr NpdrmKeys kNpdrmKeys = {{{npdrm}}};" if npdrm else "constexpr NpdrmKeys kNpdrmKeys{};",
              f"constexpr PkgKeys kPkgKeys = {{{pkg}}};" if pkg else "constexpr PkgKeys kPkgKeys{};",
              f"constexpr SysmoduleKey kSysmoduleKey = {{{c_bytes(sysmodule.hex(), 16)}, true}};" if sysmodule
              else "constexpr SysmoduleKey kSysmoduleKey{};",
              "} // namespace", "",
              "std::span<const SelfKey> builtin_self_keys() { return std::span<const SelfKey>(kKeys).subspan(1); }",
              "const PackageKey& builtin_package_key() { return kPackageKey; }",
              "const NpdKeys& builtin_npd_keys() { return kNpdKeys; }",
              "const NpdrmKeys& builtin_npdrm_keys() { return kNpdrmKeys; }",
              "const PkgKeys& builtin_pkg_keys() { return kPkgKeys; }",
              "const SysmoduleKey& builtin_sysmodule_key() { return kSysmoduleKey; }", "",
              "} // namespace pspocket::recomp"]
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    where = f"from {vault}" if vault else f"none: no Crypto/key_vault.cpp under {root}"
    print(f"self-keys: {count} SELF keys, {'the' if package else 'no'} package key, {'the' if npd else 'no'} NPD keys, "
          f"{'the' if npdrm else 'no'} NPDRM keys, {'the' if pkg else 'no'} PKG keys {where}, and "
          f"{'the' if sysmodule else 'no'} sysmodule key")
    return 0


if __name__ == "__main__":
    sys.exit(main())
