#!/usr/bin/env python3
"""Copies RPCS3's own NPDRM and package functions out of its source, for pspocket's differential tests (D-580,
D-583).

usage: rpcs3-extract.py RPCS3_CRYPTO_DIR OUT.inc

RPCS3_CRYPTO_DIR is RPCS3's rpcs3/Crypto directory. OUT.inc receives, verbatim, the definitions of the functions and
structures listed below (each after a #line naming its file), for tests/common/rpcs3_ref/rpcs3_ref.cpp to compile
around shims of the few RPCS3 types they use. The whole files cannot be compiled outside RPCS3 (they pull in its file
system, logging and emulator state), the functions can. The output goes in the build directory only: it is RPCS3's
code and holds no keys, but it is not pspocket's to keep (and the keys it uses come from RPCS3's key_vault.h at build
time, as everywhere else).

A missing function fails the script: the tests are only worth something when they run RPCS3's code.
"""
import pathlib
import re
import sys

# (file, kind, name): kind "function" copies a definition (a free function, or Class::method), "struct" a structure,
# "enum" the enumeration that holds the enumerator `name`, "lines" every line that matches the regular expression
# `name`.
WANTED = [
    ("unedat.h", "lines", r"^constexpr u32 (SDAT_FLAG|EDAT_\w+)\s*=.*;"),
    ("unedat.h", "struct", "NPD_HEADER"),
    ("unedat.h", "struct", "EDAT_HEADER"),
    ("utils.cpp", "function", "aescbc128_decrypt"),
    ("utils.cpp", "function", "aescbc128_encrypt"),
    ("utils.cpp", "function", "aesecb128_encrypt"),
    ("utils.cpp", "function", "cmac_hash_compare"),
    ("utils.cpp", "function", "cmac_hash_forge"),
    ("utils.cpp", "function", "hmac_hash_forge"),
    ("key_vault.cpp", "function", "rap_to_rif"),
    ("unedat.cpp", "function", "generate_key"),
    ("unedat.cpp", "function", "generate_hash"),
    ("unedat.cpp", "function", "decrypt"),
    ("unedat.cpp", "function", "dec_section"),
    ("unedat.cpp", "function", "get_block_key"),
    ("unedat.cpp", "function", "decrypt_block"),
    ("unedat.cpp", "function", "validate_dev_klic"),
    ("unedat.cpp", "function", "validate_npd_hashes"),
    ("unedat.cpp", "function", "read_npd_edat_header"),
    ("unself.cpp", "function", "SELFDecrypter::DecryptNPDRM"),
    ("unpkg.h", "enum", "PKG_MAX_FILENAME_SIZE"),
    ("unpkg.h", "enum", "PKG_RELEASE_TYPE_RELEASE"),
    ("unpkg.h", "struct", "PKGHeader"),
    ("unpkg.h", "struct", "PKGEntry"),
    ("unpkg.cpp", "function", "leaves_directory"),
    ("unpkg.cpp", "function", "package_reader::read_entries"),
    ("unpkg.cpp", "function", "package_reader::archive_read_block"),
    ("unpkg.cpp", "function", "package_reader::decrypt"),
]


def block_end(text: str, start: int) -> int:
    """The index just past the brace block that opens at or after `start`, skipping comments and literals."""
    depth = 0
    i = text.index("{", start)
    while i < len(text):
        c = text[i]
        if text.startswith("//", i):
            i = text.index("\n", i)
            continue
        if text.startswith("/*", i):
            i = text.index("*/", i) + 2
            continue
        if c in "\"'":
            j = i + 1
            while text[j] != c:
                j += 2 if text[j] == "\\" else 1
            i = j + 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced braces")


def find(text: str, kind: str, name: str):
    """[(offset, copied text)] for one wanted entry, or None."""
    if kind == "lines":
        found = list(re.finditer(name, text, re.M))
        return [(m.start(), m.group(0)) for m in found] or None
    if kind == "enum":
        m = re.search(r"^enum\b[^;{]*\{[^}]*\b" + re.escape(name) + r"\b[^}]*\};", text, re.M)
        return [(m.start(), m.group(0))] if m else None
    if kind == "struct":
        m = re.search(r"^struct\s+" + re.escape(name) + r"\b[^;{]*\{", text, re.M)
        if not m:
            return None
        end = text.index(";", block_end(text, m.start())) + 1
        return [(m.start(), text[m.start():end])]
    # A definition at the start of a line: a return type, the name, its parameters, then its body (not a declaration).
    pattern = r"^[A-Za-z_][\w:<>,\s\*&]*?\b" + re.escape(name) + r"\s*\(([^;{}]|\n)*?\)\s*(const\s*)?\{"
    m = re.search(pattern, text, re.M)
    if not m:
        return None
    return [(m.start(), text[m.start():block_end(text, m.end() - 1)])]


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip().splitlines()[2], file=sys.stderr)
        return 64
    crypto, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    lines = ["// Generated by scripts/rpcs3-extract.py from RPCS3's rpcs3/Crypto: RPCS3's own code (GPLv2), for the",
             "// differential tests only. Build directory only: never commit.", ""]
    texts = {}
    for file, kind, name in WANTED:
        if file not in texts:
            texts[file] = (crypto / file).read_text(encoding="utf-8")
        text = texts[file]
        pieces = find(text, kind, name)
        if pieces is None:
            print(f"rpcs3-extract: {name} not found in {crypto / file}", file=sys.stderr)
            return 1
        for offset, copied in pieces:
            lines.append(f'#line {text.count(chr(10), 0, offset) + 1} "{(crypto / file).as_posix()}"')
            lines.append(copied)
        lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    result = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != result:
        out.write_text(result, encoding="utf-8")
    print(f"rpcs3-extract: {len(WANTED)} definitions from {crypto}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
